def weakest_link(r) -> str:
    """Data-driven identification of the weakest evidence axis for a target."""
    problems = []
    if r.get("crispr_tier") != "A_secondary_validated":
        problems.append("CRISPR effect comes from the genome-wide screen only and was never re-tested "
                        "in the focused secondary library")
    if not bool(r.get("crispr_d4_concordant")):
        problems.append("the day-4 timepoint does not independently support the day-15 effect")
    if not bool(r.get("human_mouse_zone_concordant")):
        problems.append("the human zonal pattern does not place it in the same zone as the mouse data")
    if pd.isna(r.get("height_n_loci")):
        problems.append("no genome-wide-significant human height association at this locus")
    if not bool(r.get("FAST_GROWTH")):
        problems.append("it is not enriched in the rapidly-growing tibia contrast")
    if not bool(r.get("has_direction_matched_compound")):
        problems.append("no available compound acts in the direction the biology calls for")
    if str(r.get("inhibitor_effect_on_maturation")) == "accelerates":
        problems.append("the tractable pharmacological direction (inhibition) would accelerate maturation, "
                        "which risks exhausting the plate rather than lengthening it")
    if not problems:
        return ("The evidence is concordant across axes; the weakest link is that the entire causal claim "
                "rests on one in vitro CD200 reporter screen, which measures a maturation set-point and "
                "not bone length.")
    return problems[0][0].upper() + problems[0][1:] + "."


def evidence_report() -> str:
    df = pd.read_csv(R / "stage12" / "all_scored_genes.csv", index_col=0)
    top = pd.read_csv(R / "stage12" / "top_25_novel_targets.csv", index_col=0)
    sets = jload(R / "stage12" / "gene_sets.json")
    comp_f = R / "stage12" / "compounds_by_target.csv"
    comp = pd.read_csv(comp_f) if comp_f.exists() else pd.DataFrame()

    L = ["# Evidence report — growth-plate target discovery", "",
         "## What this analysis does and does not claim", "",
         "This pipeline ranks genes by *causal evidence that they shift growth-plate chondrocyte",
         "maturation*, combined with human conservation, height genetics and druggability. Three",
         "constraints are built into the scoring rather than added as caveats:", "",
         "1. **A marker is never treated as causal.** Only genes with a reproducible CRISPR knockout",
         "   effect are eligible; expression evidence can only modulate the score of a gene that",
         "   already has one.",
         "2. **Faster maturation is never equated with greater final length.** Longitudinal growth is",
         "   the integral of chondrocyte output until the plate senesces, so accelerating maturation",
         "   can shorten the bone. Genes whose only tractable pharmacology accelerates maturation are",
         "   penalised through an explicit plate-exhaustion term.",
         "3. **No dosing or self-experimentation guidance is given anywhere in these outputs.**", "",
         "## Direction logic", "",
         "The screen's log-fold change is measured between the top and bottom 10% of CD200-expressing",
         "cells. Stage 02 established from GSE225879 that CD200-high cells are the matured",
         "(prehypertrophic/osteogenic), post-mitotic population — prehypertrophic panel +3.27,",
         "hypertrophic +2.37, cell-cycle −0.38 (p = 0.002) — so:", "",
         "| screen LFC | what the gene normally does | effect of an inhibitor | interpretation |",
         "|---|---|---|---|",
         "| positive | restrains maturation | accelerates maturation | risks premature plate exhaustion → penalised |",
         "| negative | drives maturation | delays hypertrophic transition | compatible with a prolonged growth window |", "",
         "## Gene sets", "", "| set | n | definition |", "|---|---:|---|",
         f"| CRISPR_CAUSAL | {len(sets.get('CRISPR_CAUSAL', []))} | reproducible knockout effect at day 4 and/or 15, "
         "after removing multi-mapping guide artifacts |",
         f"| FAST_GROWTH | {len(sets.get('FAST_GROWTH', []))} | enriched in young tibia and/or tibia vs phalanx, with zone annotation |",
         f"| HUMAN_CONSERVED | {len(sets.get('HUMAN_CONSERVED', []))} | same top zone in human and mouse *and* genome-wide height association |",
         f"| TRACTABLE | {len(sets.get('TRACTABLE', []))} | actionable protein class or a tractable modality bucket |",
         f"| COMPOUND_MAPPED | {len(sets.get('COMPOUND_MAPPED', []))} | at least one curated ChEMBL/DGIdb interaction |",
         f"| BLACKLIST | {len(sets.get('BLACKLIST', []))} | essential, oncogenic, pleiotropic, plate-disorganising, or unsuitable chronic pharmacology |",
         "", "## Top novel targets", ""]

    for rank, (g, r) in enumerate(top.iterrows(), 1):
        sub = comp[comp.mouse_gene == g] if not comp.empty else pd.DataFrame()
        best = None
        if not sub.empty:
            s2 = sub.copy()
            s2["p"] = pd.to_numeric(s2.get("pchembl_best"), errors="coerce")
            matched = s2[s2.get("direction_matches_desired") == True]  # noqa: E712
            pick = matched if not matched.empty else s2
            pick = pick.sort_values("p", ascending=False)
            best = pick.iloc[0]
        L += [f"### {rank}. {g} ({r.get('human_gene')})", "",
              f"- **Score** {r.get('total_score'):.2f} (potential {r.get('score_positive'):.2f}, "
              f"risk {r.get('score_penalty'):.2f}); CRISPR tier `{r.get('crispr_tier')}`",
              f"- **Screen evidence** day-15 LFC "
              f"{r.get('crispr_lfc_secondary_D15') if pd.notna(r.get('crispr_lfc_secondary_D15')) else r.get('crispr_lfc_primary_D15'):+.3f}"
              f", guide consistency {r.get('crispr_guide_consistency_D15')}, "
              f"day-4 concordant: {bool(r.get('crispr_d4_concordant'))}, "
              f"cross-library agreement: {bool(r.get('crispr_cross_library_agree'))}",
              f"- **Screen effect** {r.get('screen_effect')}",
              f"- **Fast growth** young-tibia log2FC "
              f"{r.get('fg_young_tibia_lfc') if pd.notna(r.get('fg_young_tibia_lfc')) else float('nan'):+.2f}"
              f", tibia vs phalanx {r.get('fg_tibia_vs_phalanx_lfc') if pd.notna(r.get('fg_tibia_vs_phalanx_lfc')) else float('nan'):+.2f}"
              f", rat-concordant: {bool(r.get('fg_rat_concordant'))}, zone bias: {r.get('fg_zone_bias')}",
              f"- **Zonal** mouse top zone `{r.get('mouse_zone_top')}`, human top zone `{r.get('human_zone_top')}`, "
              f"concordant: {bool(r.get('human_mouse_zone_concordant'))}; single-cell consensus state "
              f"`{r.get('sc_consensus_state')}` ({r.get('sc_n_datasets_agree')} of {r.get('sc_n_datasets_detected')} datasets)",
              f"- **Human height genetics** "
              + (f"{int(r.get('height_n_loci'))} independent loci, best p = 1e-{r.get('height_neglog10p'):.0f}"
                 if pd.notna(r.get("height_n_loci")) else "no genome-wide-significant association"),
              f"- **Literature** {int(r.get('pubmed_growthplate')) if pd.notna(r.get('pubmed_growthplate')) else 'n/a'} "
              f"growth-plate papers of {int(r.get('pubmed_total')) if pd.notna(r.get('pubmed_total')) else 'n/a'} total",
              f"- **Desired intervention direction** {r.get('desired_intervention_direction')}",
              ]
        if best is not None and isinstance(best.get("compound"), str):
            direct = best.get("direct_interaction")
            L += [f"- **Strongest current compound** {best.get('compound')} "
                  f"({best.get('source')}; direction `{best.get('compound_direction_class')}`, "
                  f"max phase {best.get('max_phase')}"
                  + (f", pChEMBL {best.get('pchembl_best')}" if pd.notna(best.get("pchembl_best")) else "")
                  + ")",
                  f"- **Directly hits the target?** "
                  + ("yes — ChEMBL records a direct interaction" if direct == 1 else
                     ("no / not recorded as direct — the interaction is curated but indirect or unannotated"
                      if pd.notna(direct) else "not recorded; DGIdb curation does not assert directness")),
                  f"- **Direction matches the desired direction?** {bool(best.get('direction_matches_desired'))}"]
        else:
            L += ["- **Strongest current compound** none in ChEMBL or DGIdb — this is a tool-compound "
                  "gap, not a validated undruggable call.",
                  "- **Directly hits the target?** n/a", "- **Direction matches?** n/a"]
        L += [f"- **Weakest link** {weakest_link(r)}",
              f"- **Single validating experiment** {experiment_for(r, g)}", ""]

    L += ["## Method summary", "",
          "- Within-dataset effects were computed before any integration; nothing was merged until",
          "  stage 10, and each line of evidence remains its own column in `all_scored_genes.csv`.",
          "- Mouse→human harmonisation used Ensembl BioMart orthologues (17,064 one-to-one).",
          "- Bulk raw-count series used PyDESeq2; normalised/CPM series used a Python reimplementation",
          "  of limma's empirical-Bayes moderated t-test. Effect sizes are reported alongside p-values.",
          "- Single-cell data were QC'd per dataset, doublet-filtered, annotated by marker panels and",
          "  pseudobulked by sample × state.",
          "- Compound evidence was pulled programmatically from ChEMBL (mechanism, action type,",
          "  directness, max phase, pChEMBL potency) and DGIdb (curated interactions, approval, sources).", ""]
    return "\n".join(L)


def experiment_for(r, gene: str) -> str:
    direction = "inhibition" if str(r.get("inhibitor_effect_on_maturation")) == "delays" else "activation"
    return (f"Chondrocyte-specific conditional {'knockout' if direction == 'inhibition' else 'gain-of-function'} "
            f"of {gene} in mouse (e.g. Col2a1-CreERT2), induced postnatally, with **tibial and femoral length "
            f"measured by radiograph or µCT at 4 and 12 weeks** as the primary endpoint, plus growth-plate "
            f"height and zone-specific BrdU/EdU labelling to show whether any length change comes from "
            f"preserved proliferative output rather than accelerated maturation. Length — not a maturation "
            f"marker — is the readout that decides this hypothesis.")


def main() -> None:
    (OUT / "dataset_qc_report.md").write_text(qc_report())
    G.log("wrote dataset_qc_report.md")
    (OUT / "evidence_report.md").write_text(evidence_report())
    G.log("wrote evidence_report.md")


if __name__ == "__main__":
    main()
