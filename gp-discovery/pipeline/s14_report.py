    L += [f"| … | | _{len(man)-14} further files in the manifest_ |", ""]
    L += ["All 63 compressed files were verified to decompress cleanly; two truncated downloads",
          "(GSE125464, GSE288529 matrices) and two more in GSE231795 were detected by that check",
          "and re-fetched before analysis.", ""]

