          f"- Cross-library replication is good: primary vs secondary screen at day 15 gives "
          f"**r = {r_cross:.3f}** (n = {int(cr.avg_lfc_sD15.notna().sum())}).",
          "- Day 15 is therefore treated as the informative timepoint and day 4 as supporting evidence.",
          f"- **Guide multi-mapping artifact:** {int(cr.multimapping_artifact.sum()):,} genes have >50% of "
